#ifndef FOC_INIT_H
#define FOC_INIT_H

#include "gpio/cy_gpio.h"
#include "trigmux/cy_trigmux.h"

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     FOC PWM 准备结果
// 参数说明     FOC_INIT_SUCCESS        两台电机的引脚、时钟、定时器都准备好了
// 参数说明     FOC_INIT_GPIO_ERROR     某个 PWM 引脚没交给定时器
// 参数说明     FOC_INIT_CLOCK_ERROR    PWM 时钟或 8 MHz 分频器不对
// 参数说明     FOC_INIT_TCPWM_ERROR    某个 PWM 定时器配置失败
// 备注信息     foc_init() 失败时用这个值区分卡在哪一步
//-------------------------------------------------------------------------------------------------------------------
typedef enum
{
    FOC_INIT_SUCCESS     = 0u,
    FOC_INIT_GPIO_ERROR  = 1u,
    FOC_INIT_CLOCK_ERROR = 2u,
    FOC_INIT_TCPWM_ERROR = 3u,
} foc_init_status_t;

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     准备两台电机的三相 PWM
// 参数说明     void
// 返回参数     foc_init_status_t       准备结果，失败时不要再启动 PWM
// 使用示例     if (foc_init() != FOC_INIT_SUCCESS) { for(;;){} }
// 备注信息     只准备，不输出波形。真正出波要再调用 foc_pwm_start()
//-------------------------------------------------------------------------------------------------------------------
foc_init_status_t foc_init(void);

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     启动两台电机的六路 PWM
// 参数说明     void
// 返回参数     void
// 使用示例     foc_pwm_start();
// 备注信息     先各自 Enable，再打公共触发线让同电机三相对齐
//              公共触发失败时退回每路 TriggerStart，保证仍能出波
//-------------------------------------------------------------------------------------------------------------------
void foc_pwm_start(void);

#endif /* FOC_INIT_H */
