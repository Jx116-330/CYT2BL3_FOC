#include "zf_common_headfile.h"
#include "foc_init.h"

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     主函数
// 备注信息     当前是板级 PWM 测试，还不是完整 FOC
//              两台电机各三相，固定约 50% 占空比、约 20 kHz、死区 1.0 us
//              电机不要接。调试看波时不要停在断点上，否则 PWM 会冻结
//
//              探点（MCU 脚，接到 FD6288T 的 HIN/LIN）：
//                电机 1  U P14.0/P14.1  V P18.4/P18.5  W P18.6/P18.7
//                电机 2  U P00.2/P00.3  V P02.0/P02.1  W P05.0/P05.1
//              期望：每相约 20 kHz、约 50%、上下桥互补、交越死区约 1 us
//              同一台电机三路上桥边沿应重合；两台电机之间不要求对齐
//-------------------------------------------------------------------------------------------------------------------
int main(void)
{
    clock_init(SYSTEM_CLOCK_160M);                                              // 必须先做，系统时钟 160 MHz
    debug_init();                                                               // 打开调试串口 UART0，115200

    if (foc_init() != FOC_INIT_SUCCESS)                                         // 只准备 PWM，此时还没有波形
    {
        printf("PWM test: foc_init failed\r\n");
        for(;;)
        {
        }
    }

    foc_pwm_start();                                                            // 六路启动，并尝试三相对齐
    printf("PWM test: 50%% 20kHz running\r\n");                                 // 串口看到这句，说明已经发出启动命令
    for(;;)
    {
    }
}
